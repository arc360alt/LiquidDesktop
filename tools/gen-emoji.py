#!/usr/bin/env python3
"""Builds renderer/js/emojidata.js for the Emoji & Symbols picker (renderer/js/emoji.js).
  python3 tools/gen-emoji.py [emoji-test.txt] [cldr-annotations-en.xml]
Without arguments it downloads both from unicode.org / the CLDR repository.
Emoji newer than MAX_VERSION are left out (the emoji font in most distributions doesn't draw them yet)."""
import re, sys, json, urllib.request, unicodedata, os

MAX_VERSION = 16.0
TEST_URL = 'https://unicode.org/Public/emoji/latest/emoji-test.txt'
CLDR_URL = 'https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotations/en.xml'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'renderer', 'js', 'emojidata.js')

def read(arg, url):
    if arg: return open(arg, encoding='utf-8').read()
    return urllib.request.urlopen(url, timeout=30).read().decode('utf-8')

test = read(sys.argv[1] if len(sys.argv) > 1 else None, TEST_URL)
cldr = read(sys.argv[2] if len(sys.argv) > 2 else None, CLDR_URL)

# keywords: <annotation cp="😀">face | grin | grinning face</annotation>
keywords = {}
for cp, words in re.findall(r'<annotation cp="([^"]+)">([^<]+)</annotation>', cldr):
    keywords[cp] = [w.strip() for w in words.split('|')]

TONES = ['\U0001F3FB', '\U0001F3FC', '\U0001F3FD', '\U0001F3FE', '\U0001F3FF']
groups, order, allq = {}, [], set()
group = None
rows = []
for line in test.splitlines():
    m = re.match(r'# group: (.+)', line)
    if m:
        group = m.group(1); continue
    m = re.match(r'^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s+(.+)$', line)
    if not m or group == 'Component': continue
    ch = ''.join(chr(int(c, 16)) for c in m.group(1).split())
    allq.add(ch)
    rows.append((group, ch, float(m.group(2)), m.group(3)))

def toned(base, tone):
    # the modifier goes after the first code point (an emoji presentation selector there is dropped)
    rest = base[1:]
    if rest.startswith('️'): rest = rest[1:]
    return base[0] + tone + rest

for group, ch, ver, name in rows:
    if ver > MAX_VERSION: continue
    if 'skin tone' in name: continue   # variants: picked from the base emoji
    if group not in groups: groups[group] = []; order.append(group)
    kw = keywords.get(ch.replace('️', ''), keywords.get(ch, []))
    words = ' '.join(sorted(set(w.lower() for w in kw if w.lower() not in name.lower())))
    tone = all(toned(ch, t) in allq for t in TONES)
    groups[group].append([ch, name, words, 1] if tone else ([ch, name, words] if words else [ch, name]))

# Symbols (not emoji): what the Mac's Character Viewer puts first — arrows, math, currency, punctuation, letters
SYMBOLS = {
    'Arrows': '←→↑↓↔↕↖↗↘↙⇐⇒⇑⇓⇔⇄⇆↩↪↺↻⤴⤵➔➜➤⇧⇪⇥⇤',
    'Technical': '⌘⌥⌃⇧⎋⏎⌫⌦⏏⌂⌨⏻⏼⏽⌚⌛⏰⏱⏲',
    'Math': '±×÷≠≈≡≤≥∞√∛∑∏∫∂∆∇∈∉∩∪⊂⊃∀∃∅∝∠⊥°′″‰‱πµΩ½⅓⅔¼¾⅛¹²³⁴ⁿ',
    'Currency': '$€£¥¢₹₽₩₪₫₱₦₴₺₸₿¤',
    'Punctuation': '“”‘’«»‹›„‚…—–•·¡¿§¶†‡※‽⁂',
    'Letterlike': '©®™℗℠℃℉№℮ℓ℞℅',
    'Shapes': '■□▪▫▲△▼▽◆◇○●◎◉★☆✦✧❖♠♣♥♦♤♧♡♢',
    'Marks': '✓✔✗✘☐☑☒✱✲✳✴✵✶✷✸❋❀✿❁',
    'Music & Weather': '♩♪♫♬♭♮♯☀☁☂☃☄★☾☽',
    'Latin': 'ÀÁÂÃÄÅÆÇÈÉÊËÌÍÎÏÐÑÒÓÔÕÖØÙÚÛÜÝÞßàáâãäåæçèéêëìíîïðñòóôõöøùúûüýþÿŒœŠšŸŽžƒ',
    'Greek': 'ΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩαβγδεζηθικλμνξοπρστυφχψω',
}
symbols = []
for sub, chars in SYMBOLS.items():
    for c in chars:
        try: nm = unicodedata.name(c).lower()
        except ValueError: nm = sub.lower()
        kw = ' '.join(w.lower() for w in keywords.get(c, []) if w.lower() not in nm)
        symbols.append([c, nm, (sub.lower() + ' ' + kw).strip()])

data = [[g, groups[g]] for g in order] + [['Special Characters', symbols]]
count = sum(len(g[1]) for g in data)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen-emoji.py from Unicode emoji-test.txt and CLDR keywords: don\'t edit by hand.\n')
    f.write('// [group, [[character, name, keywords?, skin tones? (1)], …]], …\n')
    f.write('export const EMOJI = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'wrote {OUT}: {count} characters in {len(data)} groups')
